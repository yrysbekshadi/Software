def puml_body(src):
    """Return (lines, raw_lines). lines have comments and block comments blanked out but keep
    their index, so raw_lines[i] can be inspected for the '  why:' comment above line i."""
    raw = src.splitlines()
    out = []
    in_block = False
    for line in raw:
        s = line
        if in_block:
            if "'/" in s:
                s = s.split("'/", 1)[1]
                in_block = False
            else:
                out.append("")
                continue
        if "/'" in s:
            before, after = s.split("/'", 1)
            if "'/" in after:
                s = before + after.split("'/", 1)[1]
            else:
                s = before
                in_block = True
        if s.strip().startswith("'"):
            s = ""
        out.append(s)
    return out, raw


def has_start_end(src):
    return "@startuml" in src and "@enduml" in src


def justified(raw_lines, idx):
    """True if the nearest non-empty line above idx is a comment containing 'why:'."""
    j = idx - 1
    while j >= 0 and not raw_lines[j].strip():
        j -= 1
    return j >= 0 and raw_lines[j].strip().startswith("'") and "why:" in raw_lines[j].lower()


ENDPOINT = r'(\([^)]*\)|:[^:]+:|"[^"]+"|[A-Za-z_][\w.]*)'
UC_ARROW = r'(<\|?|\*|o)?([-.]+)(?:(?:left|right|up|down|le|ri|l|r|u|d)[-.]*)?(\|?>|\*|o)?'


