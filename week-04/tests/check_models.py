def main():
    parser = argparse.ArgumentParser(description="Structural checks over week-04/models/ and lab-report.md")
    parser.add_argument("--json", action="store_true", help="machine-readable output for the grading pipeline")
    args = parser.parse_args()

    if not (os.path.isdir("models") and os.path.isdir("tests")):
        if args.json:
            print(json.dumps({"ok": False, "reason": "wrong-directory"}))
        else:
            print("Run this from inside your week-04 folder:\n")
            print("    cd week-04")
            print("    python tests/check_models.py")
        return 2

    uc = check_usecase(os.path.join("models", "use-case.puml"),
                       os.path.join("models", "original", "use-case.puml"))
    cl = check_class(os.path.join("models", "class.puml"))

    seq_present = os.path.isfile(os.path.join("models", "sequence.puml"))
    act_present = os.path.isfile(os.path.join("models", "activity.puml"))
    if not seq_present and not act_present:
        record("BH0", "ERROR", "no behaviour diagram - add models/sequence.puml OR models/activity.puml")
    if seq_present:
        check_sequence(os.path.join("models", "sequence.puml"))
    if act_present:
        check_activity(os.path.join("models", "activity.puml"))

    # originals and images for every revised diagram present
    missing_orig, missing_img = [], []
    stems = ["use-case", "class"] + (["sequence"] if seq_present else []) + (["activity"] if act_present else [])
    imgs = os.listdir(os.path.join("models", "img")) if os.path.isdir(os.path.join("models", "img")) else []
    for stem in stems:
        if not os.path.isfile(os.path.join("models", stem + ".puml")):
            continue
        if not os.path.isfile(os.path.join("models", "original", stem + ".puml")):
            missing_orig.append("original/%s.puml" % stem)
        if not any(f.startswith(stem + ".") and f.lower().endswith((".png", ".svg")) for f in imgs):
            missing_img.append("img/%s.png|svg" % stem)
    if not any(os.path.isfile(os.path.join("models", st + ".puml")) for st in stems):
        record("FI1", "ERROR", "no diagrams in models/ yet")
        record("FI2", "ERROR", "no diagrams in models/ yet")
    else:
        record("FI1", "FAIL" if missing_orig else "PASS",
               "missing: " + ", ".join(missing_orig) if missing_orig else "the AI's original output is kept for every diagram")
        record("FI2", "FAIL" if missing_img else "PASS",
               "missing rendered image: " + ", ".join(missing_img) if missing_img else "a rendered image for every diagram")

    check_worksheet(uc, cl, seq_present, act_present)

    counts = {v: sum(1 for _, x, _ in RESULTS if x == v) for v in ("PASS", "FAIL", "ERROR")}
    ok = counts["FAIL"] == 0 and counts["ERROR"] == 0
    if args.json:
        rows = [{"id": cid, "title": TITLES.get(cid, cid), "verdict": v, "message": m} for cid, v, m in RESULTS]
        print(json.dumps({"ok": ok, "counts": counts, "rows": rows,
                          "behaviour_diagram": "both" if seq_present and act_present else
                          "sequence" if seq_present else "activity" if act_present else "none"},
                         ensure_ascii=False, indent=2))
        return 0 if ok else 1

    print("Week 04 structural check - shape only, never quality\n")
    for cid, verdict, msg in RESULTS:
        print("%-4s %-5s %s" % (cid, verdict, msg))
    if seq_present and act_present:
        print("\nBoth behaviour diagrams present - the optional extension; both were checked.")
    print("\nSUMMARY pass=%d fail=%d error=%d" % (counts["PASS"], counts["FAIL"], counts["ERROR"]))
    print("A FAIL you report and explain in lab-report.md §9 costs you nothing. One you hide costs the criterion.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
