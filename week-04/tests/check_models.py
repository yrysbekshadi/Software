def check_activity(path):
    ids = ("AC1", "AC2", "AC3", "AC4", "AC5", "AC6")
    src = read(path)
    if src is None:
        for cid in ids:
            record(cid, "ERROR", "models/activity.puml not found")
        return
    if not has_start_end(src):
        for cid in ids:
            record(cid, "ERROR", "models/activity.puml has no @startuml / @enduml")
        return
    lines, raw = puml_body(src)
    body = [l.strip() for l in lines]
    has_start = any(re.match(r'^start$', l) or l.startswith("(*)") for l in body)
    has_stop = any(re.match(r'^(stop|end|kill|detach)$', l) or "(*)" in l[1:] for l in body)
    record("AC1", "PASS" if has_start and has_stop else "FAIL",
           "initial and final nodes present" if has_start and has_stop
           else "missing %s" % " and ".join(x for x, ok in (("start", has_start), ("stop", has_stop)) if not ok))

    decisions = [(i, l) for i, l in enumerate(body) if re.match(r'^(if|elseif)\s*\(', l)]
    dtext = [norm(l) for i, l in decisions]
    need = {"time range (R1)": ("time", "duration", "start", "future", "range", "r1"),
            "blocked room (R3)": ("block", "r3"),
            "overlap (R2)": ("overlap", "conflict", "free", "availab", "r2")}
    missing = [k for k, words in need.items() if not any(any(w in d for w in words) for d in dtext)]
    record("AC2", "FAIL" if missing else "PASS",
           "no decision checks: " + ", ".join(missing) if missing
           else "separate decisions check R1, R3 and R2 (%d decisions)" % len(decisions))

    unguarded = []
    for i, l in enumerate(body):
        if re.match(r'^(if|elseif)\s*\(', l) and not re.search(r'then\s*\(\s*[^)\s][^)]*\)', l):
            unguarded.append("line %d then" % (i + 1))
        if re.match(r'^else\b', l) and not re.match(r'^else\s*\(\s*[^)\s][^)]*\)', l):
            unguarded.append("line %d else" % (i + 1))
    if not decisions:
        record("AC3", "FAIL", "no decisions at all")
    else:
        record("AC3", "FAIL" if unguarded else "PASS",
               "unlabelled guard(s): " + ", ".join(unguarded) if unguarded else "every branch has a labelled guard")

    forks = [i for i, l in enumerate(body) if re.match(r'^(fork|split)\b', l)]
    record("AC4", "FAIL" if forks else "PASS",
           "parallel fork/split used - the checks are sequential; use branches" if forks
           else "no parallel paths")

    actions = " ".join(l for l in body if l.startswith(":")).lower()
    conf = "confirm" in actions
    rej = "reject" in actions or "refus" in actions or "deny" in actions
    record("AC5", "PASS" if conf and rej else "FAIL",
           "confirmation on success, rejection on failure" if conf and rej
           else "missing action: " + ", ".join(x for x, ok in (("confirmation", conf), ("rejection", rej)) if not ok))

    create_idx = [i for i, l in enumerate(body) if l.startswith(":") and re.search(r"create|save|insert|store|persist|reserve", l, re.I)]
    rule_idx = [i for i, l in decisions if any(any(w in norm(l) for w in ws) for ws in need.values())]
    if not create_idx:
        record("AC6", "FAIL", "no action creates the booking")
    elif rule_idx and create_idx[0] < max(rule_idx):
        record("AC6", "FAIL", "the booking is created before every rule has been checked")
    else:
        record("AC6", "PASS", "creation comes after all rule checks")


