CL_ARROW = r'([<*o]?\|?[-.]+(?:(?:left|right|up|down|l|r|u|d)[-.]+)?\|?[>*o]?)'


def parse_class(src):
    lines, raw = puml_body(src)
    classes = {}     # name -> list of member lines
    aliases = {}
    relations = []   # (left, lmult, arrow, rmult, right, label, idx)
    notes = []
    current = None
    in_note = False
    note_buf = []
    for i, line in enumerate(lines):
        s = line.strip()
        if in_note:
            if re.match(r'^end\s*note', s):
                notes.append(" ".join(note_buf))
                note_buf = []
                in_note = False
            else:
                note_buf.append(s)
            continue
        if not s:
            continue
        if current is not None:
            if s.startswith("}"):
                current = None
            else:
                classes[current].append(s)
            continue
        m = re.match(r'^note\b(.*)$', s)
        if m:
            rest = m.group(1)
            if ":" in rest:
                notes.append(rest.split(":", 1)[1])
            else:
                in_note = True
            continue
        m = re.match(r'^(?:abstract\s+class|abstract|class|entity|enum|interface)\s+(?:"([^"]+)"|([\w.]+))'
                     r'(?:\s+as\s+([\w.]+))?[^{]*(\{)?\s*(\})?', s)
        if m:
            name = m.group(1) or m.group(2)
            classes.setdefault(name, [])
            if m.group(3):
                aliases[m.group(3)] = name
            if m.group(4) and not m.group(5):
                current = name
            continue
        m = re.match(r'^("?[\w.]+"?)\s*(?:"([^"]*)")?\s*' + CL_ARROW + r'\s*(?:"([^"]*)")?\s*("?[\w.]+"?)\s*(?::\s*(.*))?$', s)
        if m and ("-" in m.group(3) or "." in m.group(3)):
            left = aliases.get(m.group(1).strip('"'), m.group(1).strip('"'))
            right = aliases.get(m.group(5).strip('"'), m.group(5).strip('"'))
            relations.append((left, m.group(2), m.group(3), m.group(4), right, m.group(6) or "", i))
            classes.setdefault(left, [])
            classes.setdefault(right, [])
    return {"classes": classes, "relations": relations, "notes": notes, "raw": raw}


def check_class(path):
    ids = ("CL1", "CL2", "CL3", "CL4", "CL5", "CL6", "CL7", "CL8")
    src = read(path)
    if src is None:
        for cid in ids:
            record(cid, "ERROR", "models/class.puml not found")
        return None
    if not has_start_end(src):
        for cid in ids:
            record(cid, "ERROR", "models/class.puml has no @startuml / @enduml")
        return None
    cl = parse_class(src)
    cmap = {norm(k): k for k in cl["classes"]}

    missing = [c for c in ("Student", "Room", "Booking") if norm(c) not in cmap]
    record("CL1", "FAIL" if missing else "PASS",
           "missing class(es): " + ", ".join(missing) if missing else "Student, Room and Booking present")

    def rel_between(a, b):
        out = []
        for r in cl["relations"]:
            if {norm(r[0]), norm(r[4])} == {norm(a), norm(b)}:
                out.append(r)
        return out

    sb = rel_between("Student", "Booking")
    rb = rel_between("Room", "Booking")
    miss_rel = [n for n, r in (("Student-Booking", sb), ("Room-Booking", rb)) if not r]
    record("CL2", "FAIL" if miss_rel else "PASS",
           "no association: " + ", ".join(miss_rel) if miss_rel else "Booking is associated with Student and with Room")

    no_mult = []
    for left, lm, arrow, rm, right, label, i in cl["relations"]:
        if "|" in arrow:
            continue
        if not (lm and lm.strip()) or not (rm and rm.strip()):
            no_mult.append("%s-%s" % (left, right))
    record("CL3", "FAIL" if no_mult else "PASS",
           "association(s) without a multiplicity at both ends: " + ", ".join(no_mult) if no_mult
           else "every association has multiplicities at both ends")

    bad = []
    for name, rels in (("Student", sb), ("Room", rb)):
        for left, lm, arrow, rm, right, label, i in rels:
            if norm(left) == norm(name):
                owner_m, booking_m = lm, rm
            else:
                owner_m, booking_m = rm, lm
            if (owner_m or "").strip() != "1":
                bad.append("%s end is %r, expected 1" % (name, owner_m))
            if (booking_m or "").strip() not in ("0..*", "*"):
                bad.append("Booking end (towards %s) is %r, expected 0..*" % (name, booking_m))
    if miss_rel:
        record("CL4", "FAIL", "cannot check multiplicities - association missing")
    else:
        record("CL4", "FAIL" if bad else "PASS",
               "; ".join(bad) if bad else "1 student / 1 room per booking, 0..* bookings per student and per room")

    unjust = []
    for left, lm, arrow, rm, right, label, i in cl["relations"]:
        kind = None
        if "|" in arrow:
            kind = "inheritance"
        elif "*" in arrow:
            kind = "composition"
        elif arrow.startswith("o") or arrow.endswith("o"):
            kind = "aggregation"
        if kind and not justified(cl["raw"], i):
            unjust.append("%s-%s (%s)" % (left, right, kind))
    record("CL5", "FAIL" if unjust else "PASS",
           "no ' why: comment directly above: " + ", ".join(unjust) if unjust
           else "every inheritance / composition / aggregation carries a ' why: comment (or there are none)")

    design_words = ("service", "repository", "controller", "screen", "page", "manager", "dao",
                    "form", "database", "ui", "view", "handler")
    design = [c for c in cl["classes"] if any(norm(c).endswith(w) or norm(c) == w for w in design_words)]
    record("CL6", "FAIL" if design else "PASS",
           "design or UI class(es) in a domain model: " + ", ".join(design) if design
           else "only domain concepts in the class diagram")

    probs = []
    bk = [norm(x) for x in cl["classes"].get(cmap.get("booking", ""), [])]
    rm_ = [norm(x) for x in cl["classes"].get(cmap.get("room", ""), [])]
    if not any("start" in x for x in bk):
        probs.append("Booking has no start attribute (R1)")
    if not any("end" in x or "duration" in x for x in bk):
        probs.append("Booking has no end or duration attribute (R1, R2)")
    if not any("status" in x or "state" in x or "active" in x or "cancel" in x for x in bk):
        probs.append("Booking has no status (R2 says *active* bookings)")
    if not any("block" in x for x in rm_):
        probs.append("Room has no blocked state (R3)")
    record("CL7", "FAIL" if probs else "PASS",
           "; ".join(probs) if probs else "attributes needed by R1-R3 are present")

    note_text = " ".join(cl["notes"]).lower()
    ok = "r2" in note_text or "overlap" in note_text
    record("CL8", "PASS" if ok else "FAIL",
           "a note states R2 (no overlapping active bookings)" if ok
           else "no note states R2 - multiplicity cannot show 'no overlap'; add a note on Booking")
    return cl


