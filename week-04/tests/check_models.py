def parse_usecase(src):
    lines, raw = puml_body(src)
    actors = {}        # key -> display name
    usecases = {}      # key -> display name
    boundary_names = []
    actors_inside = []
    links = []         # (a_key, b_key, arrow, label, line_index)
    depth = 0
    boundary_depths = []

    def add_uc(name, alias=None):
        key = alias or name
        usecases[key] = name
        usecases.setdefault(name, name)
        return key

    def resolve(ep):
        ep = ep.strip()
        if ep.startswith("(") and ep.endswith(")"):
            name = ep[1:-1].strip()
            if name not in usecases:
                add_uc(name)
            return name, "uc"
        if ep.startswith(":") and ep.endswith(":"):
            name = ep[1:-1].strip()
            actors.setdefault(name, name)
            return name, "actor"
        if ep.startswith('"') and ep.endswith('"'):
            ep = ep[1:-1]
        if ep in actors:
            return ep, "actor"
        if ep in usecases:
            return ep, "uc"
        return ep, "unknown"

    for i, line in enumerate(lines):
        s = line.strip()
        if not s:
            continue
        m = re.match(r'^(rectangle|package|frame|node|folder)\s+(?:"([^"]+)"|([\w.]+))?[^{]*\{', s)
        if m:
            name = m.group(2) or m.group(3) or ""
            boundary_names.append(name)
            boundary_depths.append(depth + 1)
        opens = s.count("{")
        closes = s.count("}")
        inside = bool(boundary_depths) and depth >= boundary_depths[0]

        m = re.match(r'^actor\s+(?:"([^"]+)"|:([^:]+):|([\w.]+))(?:\s+as\s+(?:"([^"]+)"|([\w.]+)))?', s)
        if m:
            name = m.group(1) or m.group(2) or m.group(3)
            alias = m.group(5) or (m.group(3) if m.group(4) else None)
            display = m.group(4) or name
            if m.group(4):          # actor Alias as "Display"
                actors[m.group(3) or name] = display
            else:
                actors[alias or name] = name
                actors.setdefault(name, name)
            if inside:
                actors_inside.append(display)
            depth += opens - closes
            continue

        m = re.match(r'^usecase\s+(?:"([^"]+)"|\(([^)]+)\)|([\w.]+))(?:\s+as\s+(?:"([^"]+)"|([\w.]+)))?', s)
        if m:
            name = m.group(1) or m.group(2) or m.group(3)
            if m.group(4):          # usecase UC1 as "Book room"
                add_uc(m.group(4), m.group(3) or name)
            else:
                add_uc(name, m.group(5))
            depth += opens - closes
            continue

        m = re.match(r'^\(([^)]+)\)\s+as\s+([\w.]+)', s)
        if m:
            add_uc(m.group(1).strip(), m.group(2))
            depth += opens - closes
            continue

        m = re.match(r'^' + ENDPOINT + r'\s*' + UC_ARROW + r'\s*' + ENDPOINT + r'\s*(?::\s*(.*))?$', s)
        if m and ("-" in (m.group(3) or "") or "." in (m.group(3) or "")):
            a, at = resolve(m.group(1))
            b, bt = resolve(m.group(5))
            arrow = (m.group(2) or "") + (m.group(3) or "") + (m.group(4) or "")
            links.append((a, at, b, bt, arrow, (m.group(6) or ""), i))
        depth += opens - closes

    return {
        "actors": actors,
        "usecases": usecases,
        "boundaries": boundary_names,
        "actors_inside": actors_inside,
        "links": links,
        "lines": lines,
        "raw": raw,
    }


REQUIRED_UC = [
    ("View availability", lambda n: "availab" in n),
    ("Book room", lambda n: "book" in n and "cancel" not in n and "block" not in n),
    ("Cancel booking", lambda n: "cancel" in n),
    ("Block / unblock room", lambda n: "block" in n),
    ("Review usage", lambda n: "usage" in n),
]


def uc_display_names(uc):
    names = set(uc["usecases"].values())
    return sorted(names)


def check_usecase(path, orig_path):
    src = read(path)
    if src is None:
        for cid in ("UC1", "UC2", "UC3", "UC4", "UC5", "UC6", "UC7", "UC8", "UC9"):
            record(cid, "ERROR", "models/use-case.puml not found")
        return None
    if not has_start_end(src):
        for cid in ("UC1", "UC2", "UC3", "UC4", "UC5", "UC6", "UC7", "UC8", "UC9"):
            record(cid, "ERROR", "models/use-case.puml has no @startuml / @enduml")
        return None

    uc = parse_usecase(src)
    actor_names = {norm(v) for v in uc["actors"].values()} | {norm(k) for k in uc["actors"]}

    missing = [a for a in ("student", "administrator") if a not in actor_names]
    record("UC1", "FAIL" if missing else "PASS",
           "missing actor(s): " + ", ".join(missing) if missing else "Student and Administrator declared")

    named = [b for b in uc["boundaries"] if b.strip()]
    record("UC2", "PASS" if named else "FAIL",
           'named system boundary: "%s"' % named[0] if named
           else 'no named boundary - use: rectangle "Smart Campus booking system" { ... }')

    if not named:
        record("UC3", "FAIL", "no boundary, so actors cannot be outside it")
    elif uc["actors_inside"]:
        record("UC3", "FAIL", "actor(s) declared inside the boundary: " + ", ".join(uc["actors_inside"]))
    else:
        record("UC3", "PASS", "all actors declared outside the boundary")

    names = uc_display_names(uc)
    missing_uc = [label for label, test in REQUIRED_UC if not any(test(norm(n)) for n in names)]
    record("UC4", "FAIL" if missing_uc else "PASS",
           "missing use case(s): " + ", ".join(missing_uc) if missing_uc
           else "all scenario goals present (%d use cases)" % len(names))

    def display(key):
        return uc["usecases"].get(key, uc["actors"].get(key, key))

    def is_actor(key, kind):
        return kind == "actor" or norm(key) in actor_names

    # actor <-> use case associations (include/extend/generalisation excluded)
    assoc = []
    for a, at, b, bt, arrow, label, i in uc["links"]:
        lab = label.lower()
        if "include" in lab or "extend" in lab or "|" in arrow:
            continue
        if is_actor(a, at) and not is_actor(b, bt):
            assoc.append((norm(display(a)), norm(display(b))))
        elif is_actor(b, bt) and not is_actor(a, at):
            assoc.append((norm(display(b)), norm(display(a))))

    bad_conf = [(ac, u) for ac, u in assoc if "confirm" in u]
    record("UC5", "FAIL" if bad_conf else "PASS",
           "an actor is associated with a confirmation use case (%s) - R4 is an outcome of booking, "
           "not an actor goal" % ", ".join("%s-%s" % p for p in bad_conf) if bad_conf
           else "no actor is associated with a confirmation use case")

    wrong = []
    for ac, u in assoc:
        if "admin" in ac and ("cancel" in u or ("book" in u and "block" not in u)):
            wrong.append("Administrator-" + u)
        if "student" in ac and ("block" in u or "usage" in u):
            wrong.append("Student-" + u)
    record("UC6", "FAIL" if wrong else "PASS",
           "association(s) the scenario does not give that actor: " + ", ".join(wrong) if wrong
           else "actor responsibilities match the scenario")

    forbidden = ("screen", "page", "button", "database", "table", "repository", "service", "api", "form")
    bad_names = [n for n in names if any(f in norm(n) for f in forbidden)]
    bad_actor = [a for a in uc["actors"].values() if norm(a) in ("system", "database", "smartcampus")]
    probs = bad_names + ["actor " + a for a in bad_actor]
    record("UC7", "FAIL" if probs else "PASS",
           "design/UI vocabulary where a user goal should be: " + ", ".join(probs) if probs
           else "use cases are goals, not screens or components")

    unjust = []
    for a, at, b, bt, arrow, label, i in uc["links"]:
        lab = label.lower()
        kind = "include" if "include" in lab else "extend" if "extend" in lab else "generalization" if "|" in arrow else None
        if kind and not justified(uc["raw"], i):
            unjust.append("line %d (%s)" % (i + 1, kind))
    record("UC8", "FAIL" if unjust else "PASS",
           "no ' why: comment directly above: " + ", ".join(unjust) if unjust
           else "every include / extend / generalization carries a ' why: comment (or there are none)")

    orig = read(orig_path)
    if orig is None:
        record("UC9", "ERROR", "models/original/use-case.puml not found - save the AI's first output there")
    elif norm(orig) == norm(src):
        record("UC9", "FAIL", "revised use-case.puml is identical to the original - Task 1 asks for a revised diagram")
    else:
        record("UC9", "PASS", "revised diagram differs from the AI's original")
    return uc


