SEQ_ARROW = r'([<xo]?<{0,2}-{1,2}>{0,2}[xo]?|[<xo]?<{0,2}-{1,2}\\{1,2}|/{1,2}-{1,2}>?)'


def parse_sequence(src):
    lines, raw = puml_body(src)
    participants = {}   # key -> display
    messages = []       # (idx, frm, to, label, branch_id)
    notes = []
    branches = []       # [guard, kind]
    stack = []
    for i, line in enumerate(lines):
        s = line.strip()
        if not s:
            continue
        m = re.match(r'^(actor|participant|boundary|control|entity|database|collections|queue)\s+'
                     r'(?:"([^"]+)"|([\w.:]+))(?:\s+as\s+([\w.]+))?', s)
        if m:
            display = m.group(2) or m.group(3)
            key = m.group(4) or display
            participants[key] = display
            participants.setdefault(display, display)
            continue
        m = re.match(r'^(alt|opt|loop|group|critical|break|par)\b\s*(.*)$', s)
        if m:
            branches.append([m.group(2), m.group(1)])
            stack.append(len(branches) - 1)
            continue
        m = re.match(r'^else\b\s*(.*)$', s)
        if m and stack:
            kind = branches[stack[-1]][1]
            branches.append([m.group(1), kind + "-else"])
            stack[-1] = len(branches) - 1
            continue
        if re.match(r'^end$', s) and stack:
            stack.pop()
            continue
        if re.match(r'^(r?h?note)\b', s):
            if ":" in s:
                notes.append(s.split(":", 1)[1])
            else:
                buf = []
                j = i + 1
                while j < len(lines) and not re.match(r'^\s*end\s*note', lines[j]):
                    buf.append(lines[j])
                    j += 1
                notes.append(" ".join(buf))
            continue
        m = re.match(r'^("[^"]+"|[\w.]+)\s*' + SEQ_ARROW + r'\s*("[^"]+"|[\w.]+)\s*(?::\s*(.*))?$', s)
        if m:
            messages.append((i, m.group(1).strip('"'), m.group(3).strip('"'), m.group(4) or "",
                             stack[-1] if stack else None))
    return {"participants": participants, "messages": messages, "notes": notes, "branches": branches}


def check_sequence(path):
    ids = ("SQ1", "SQ2", "SQ3", "SQ4", "SQ5", "SQ6", "SQ7")
    src = read(path)
    if src is None:
        for cid in ids:
            record(cid, "ERROR", "models/sequence.puml not found")
        return None
    if not has_start_end(src):
        for cid in ids:
            record(cid, "ERROR", "models/sequence.puml has no @startuml / @enduml")
        return None
    sq = parse_sequence(src)
    disp = [norm(v) for v in sq["participants"].values()]
    missing = [p for p in ("Student", "BookingService", "BookingRepository")
               if not any(norm(p) in d for d in disp)]
    record("SQ1", "FAIL" if missing else "PASS",
           "missing lifeline(s): " + ", ".join(missing) if missing
           else "Student, BookingService and BookingRepository lifelines present")

    alts = [b for b in sq["branches"] if b[1] in ("alt", "alt-else")]
    guarded = [b for b in alts if b[0].strip()]
    ok = len([b for b in alts if b[1] == "alt"]) >= 1 and len(alts) >= 2 and len(guarded) == len(alts)
    record("SQ2", "PASS" if ok else "FAIL",
           "alt block with a guard on every branch (%d branches)" % len(alts) if ok
           else "need an alt block with at least two branches, each with a guard like [created] / [unavailable]")

    create_re = re.compile(r"create|save|insert|persist|store|reserve|trycreate", re.I)
    valid_re = re.compile(r"valid|check|rule|verif", re.I)
    first_create = next((k for k, msg in enumerate(sq["messages"]) if create_re.search(msg[3])), None)
    first_valid = next((k for k, msg in enumerate(sq["messages"]) if valid_re.search(msg[3])), None)
    if first_create is None:
        record("SQ3", "FAIL", "no message creates or saves the booking")
    elif first_valid is None or first_valid > first_create:
        record("SQ3", "FAIL", "no validation message before the first create/save message")
    else:
        record("SQ3", "PASS", "validation happens before creation")

    fail_re = re.compile(r"invalid|fail|conflict|unavail|block|reject|overlap|error|not|deny|denied", re.I)
    leaks = []
    for idx, frm, to, label, b in sq["messages"]:
        if b is not None and fail_re.search(sq["branches"][b][0]) and create_re.search(label) \
                and not re.search(r"trycreate", label, re.I):
            leaks.append(label.strip())
    record("SQ4", "FAIL" if leaks else "PASS",
           "a failure branch still creates/saves: " + "; ".join(leaks) if leaks
           else "nothing is saved on a failure branch")

    unlabeled = [msg for msg in sq["messages"] if not msg[3].strip()]
    record("SQ5", "FAIL" if unlabeled else "PASS",
           "%d message(s) without a label" % len(unlabeled) if unlabeled else "every message is labelled")

    text = " ".join([m[3] for m in sq["messages"]] + [b[0] for b in sq["branches"]] + sq["notes"]).lower()
    ntext = norm(text)
    r1 = any(w in ntext for w in ("r1", "timerange", "duration", "future"))
    record("SQ6", "PASS" if r1 else "FAIL",
           "R1 (time range) is visible - checked or stated as a precondition" if r1
           else "R1 is invisible - validate the time range or state it as a precondition in a note")
    r3 = "block" in text or "r3" in text
    record("SQ7", "PASS" if r3 else "FAIL",
           "R3 (blocked room) is visible" if r3
           else "R3 is invisible - where is the blocked-room check? a message, a guard or a note")
    return sq


