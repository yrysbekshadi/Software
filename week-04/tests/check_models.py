def norm(text):
    """Lowercase and strip everything that is not a letter or a digit."""
    return re.sub(r"[^a-z0-9]", "", (text or "").lower())


def read(path):
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return None


