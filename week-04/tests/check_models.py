def sections(md):
    out = {}
    cur = None
    for line in md.splitlines():
        m = re.match(r'^##\s+(\d+)\.', line)
        if m:
            cur = int(m.group(1))
            out[cur] = []
            continue
        if cur is not None:
            out[cur].append(line)
    return {k: "\n".join(v) for k, v in out.items()}


def table_rows(text):
    rows = []
    for line in text.splitlines():
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if all(re.match(r'^:?-{3,}:?$', c) for c in cells if c):
            continue
        rows.append(cells)
    return rows[1:] if rows else []   # drop header


def filled(row):
    return all(c and not re.search(r"<[^>]*>", c) for c in row)


def check_worksheet(uc, cl, seq_present, act_present):
    md = read("lab-report.md")
    ids = ("LR1", "LR2", "LR3", "LR4", "LR5", "LR6", "LR7", "CS1", "CS2", "CS3")
    if md is None:
        for cid in ids:
            record(cid, "ERROR", "lab-report.md not found")
        return
    sec = sections(md)

    setup = {r[0].lower(): r[1] for r in table_rows(sec.get(1, "")) if len(r) >= 2}
    need = ("name", "ai assistant", "exact model", "behaviour diagram")
    empty = [k for k in need if not setup.get(k) or re.search(r"<[^>]*>", setup.get(k, ""))]
    record("LR1", "FAIL" if empty else "PASS",
           "§1 not filled: " + ", ".join(empty) if empty else "§1 setup filled (tool and model recorded)")

    s2 = sec.get(2, "")
    blocks = re.findall(r"```[a-z]*\n(.*?)```", s2, re.S)
    real = [b for b in blocks if b.strip() and not re.search(r"<[^>]*>", b)]
    record("LR2", "PASS" if len(real) >= 4 else "FAIL",
           "%d prompts pasted in §2" % len(real) if len(real) >= 4
           else "§2 needs the task 1, 2, 3 and critique prompts pasted (found %d)" % len(real))

    r3 = [r for r in table_rows(sec.get(3, "")) if filled(r)]
    record("LR3", "PASS" if len(r3) >= 2 else "FAIL",
           "%d use-case findings in §3" % len(r3) if len(r3) >= 2 else "§3 needs at least 2 filled findings (found %d)" % len(r3))

    s4 = sec.get(4, "")
    rel_rows = [r for r in table_rows(s4.split("### 4.2")[0]) if filled(r)]
    assum = re.findall(r"^\s*-\s*A\d+\s*:\s*(.+)$", s4, re.M)
    assum = [a for a in assum if not re.search(r"<[^>]*>", a)]
    probs = []
    if len(rel_rows) < 2:
        probs.append("§4.1 needs every association read both ways (found %d rows)" % len(rel_rows))
    if not assum:
        probs.append("§4.3 declares no assumption")
    record("LR4", "FAIL" if probs else "PASS",
           "; ".join(probs) if probs else "§4 relationships read both ways, %d assumption(s) declared" % len(assum))

    s5 = sec.get(5, "")
    r5 = [r for r in table_rows(s5) if filled(r)]
    record("LR5", "PASS" if r5 else "FAIL",
           "%d behaviour-diagram findings in §5" % len(r5) if r5 else "§5 needs at least 1 filled finding")

    r6 = [r for r in table_rows(sec.get(6, "")) if filled(r)]
    verdicts = [r for r in r6 if len(r) >= 4 and re.search(r"accept|reject", r[3], re.I)]
    record("LR6", "PASS" if len(verdicts) >= 3 else "FAIL",
           "%d critique issues with a verdict" % len(verdicts) if len(verdicts) >= 3
           else "§6 needs at least 3 critique rows with accept / reject (found %d)" % len(verdicts))

    r8 = [r for r in table_rows(sec.get(8, "")) if filled(r)]
    diagrams = " ".join(r[1].lower() for r in r8 if len(r) > 1)
    miss = [d for d, ws in (("use case", ("use",)), ("class", ("class",)),
                            ("behaviour", ("seq", "activ", "behav"))) if not any(w in diagrams for w in ws)]
    ok = len(r8) >= 3 and not miss
    record("LR7", "PASS" if ok else "FAIL",
           "%d change-log rows covering all three diagrams" % len(r8) if ok
           else "§8 needs >= 3 rows and one per diagram (rows: %d, missing: %s)" % (len(r8), ", ".join(miss) or "-"))

    # consistency
    stories = read(os.path.join("models", "approved-stories.md"))
    story_ids = set(re.findall(r"\bUS-\d+\b", stories or ""))
    if stories is None:
        record("CS1", "ERROR", "models/approved-stories.md not found")
    else:
        record("CS1", "PASS" if story_ids else "FAIL",
               "%d approved stories" % len(story_ids) if story_ids else "no story IDs (US-01 ...) in approved-stories.md")

    r7 = [r for r in table_rows(sec.get(7, "")) if filled(r)]
    firsts = [norm(r[0]) for r in r7]
    miss_r = [r for r in ("r1", "r2", "r3", "r4") if not any(f.startswith(r) for f in firsts)]
    record("CS2", "FAIL" if miss_r else "PASS",
           "§7 has no filled row for: " + ", ".join(x.upper() for x in miss_r) if miss_r
           else "§7 traces R1-R4 into the diagrams")

    if uc is None:
        record("CS3", "ERROR", "use-case diagram missing, cannot trace")
    elif stories is None:
        record("CS3", "ERROR", "approved-stories.md missing, cannot trace")
    else:
        untraced = []
        for name in uc_display_names(uc):
            hit = False
            for r in r7:
                if len(r) >= 2 and norm(r[1]) == norm(name):
                    ids_in = set(re.findall(r"\bUS-\d+\b", r[0]))
                    if ids_in and ids_in <= story_ids:
                        hit = True
            if not hit:
                untraced.append(name)
        record("CS3", "FAIL" if untraced else "PASS",
               "use case(s) with no §7 row tracing to an approved story: " + ", ".join(untraced) if untraced
               else "every use case traces to an approved story")

    if seq_present and cl is not None:
        sq = parse_sequence(read(os.path.join("models", "sequence.puml")) or "")
        cls = {norm(c) for c in cl["classes"]}
        extra = []
        for d in set(sq["participants"].values()):
            base = d.split(":")[-1].strip()
            if norm(base) not in cls and norm(base) not in ("student", "administrator"):
                extra.append(base)
        unexplained = [e for e in extra if norm(e) not in norm(s5)]
        record("CS4", "FAIL" if unexplained else "PASS",
               "lifeline(s) neither in the class diagram nor explained in §5: " + ", ".join(sorted(unexplained))
               if unexplained else "every lifeline is a domain class or an explained design component")


